# receive and print log messages
# every running copy will get the messages
# published log messages are broadcasted to all receivers

import pika

connection = pika.BlockingConnection(pika.ConnectionParameters('localhost')) 
channel = connection.channel()

channel.exchange_declare(exchange='logs', exchange_type='fanout')

# we need all log messages and we are only interested in currently flowing messages
result = channel.queue_declare( queue='', # 1. whenever we connect we need a fresh empty queue - random name generated by server
                                exclusive=True) # 2. consumer connection is closed, queue should be deleted

# tell exchange to send messages to our queue = binding
channel.queue_bind(exchange='logs', queue=result.method.queue)

print(' [*] Waiting for messages. To exit press CTRL+C')

def callback(ch, method, properties, body):
    print(" [x] %r" % body)

channel.basic_consume(queue=result.method.queue, on_message_callback=callback, auto_ack=True)
channel.start_consuming()